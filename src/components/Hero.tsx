interface SceneLayer {
  id: string;
  z: number; // resting depth (negative = deeper into the box)
  w?: number; // PROJECTED width at p=0, % of stage width — the screen-space floor has no box, so it has none
  ar?: number; // aspect ratio w/h
  x?: number; // projected offset from stage center, % of stage width
  y?: number; // projected offset from stage center, % of stage height
  rot?: number;
  op?: number;
  mask?: string; // CSS mask url — /hero/*.png slot or data-URI
  tone?: string; // ink color for this layer's art — a masked fill, or the colour a renderer draws in
  ascii?: string; // built /hero/*.png mask, rendered as a hoverable ascii mosaic instead of a CSS mask
  asciiLight?: string; // alternate `ascii` source swapped in under the light theme
  ink?: number; // per-layer screen ink strength (see HeroAsciiArt's `ink`)
  dolly?: number; // share of the camera's travel this layer receives, 1 = full. Below 1 holds it back in the distance
  fade?: number; // % of the layer's width dissolved at each side, so its cut edges never resolve
  render?: 'ascii' | 'lines' | 'dots' | 'cross' | 'dither'; // which renderer draws `ascii` — symbol mosaic (default), engraving line screen, halftone dot screen, stitched glyph screen, or the art as-authored with a hover glitch
  fray?: number; // 'dither' layers: ink density (0..1) below which the plate comes apart into marks
  glitch?: boolean; // 'cross' layers only: dresses this layer's cursor patch in the accent instead of merely brightening it (see HeroAsciiArt's `glitch`)
  maskLight?: string; // alternate mask swapped in under the light theme
  toneLight?: string; // fill for the light-theme variant
  idle?: 'float' | 'float-b' | 'float-c' | 'hands'; // idle-animation role
  /* Paint slot, when it must differ from `z`. The stack is sorted by depth,
   * which is right for everything that flies at the camera together — but
   * the ground does not fly, so its resting depth stops describing where it
   * belongs in the order the moment the dolly starts. See the floor. */
  order?: number;
  kind?: 'interior' | 'halo' | 'floor' | 'spark';
  spark?: 'star' | 'light'; // particle flavor: ink sparkle vs glowing light
  lightc?: string; // glow color family for 'light' sparks
  dur?: number; // spark twinkle duration
  delay?: number; // spark twinkle phase offset
  flick?: number; // which twinkle rhythm (0-2) — see the hl-twinkle keyframes
  band?: number; // which SPARK_BANDS field this star re-rolls within
}

