/* THE LENS. Perspective distance in px — the focal length of the whole
 * scene. Shorter is wider: the same layers at the same depths, seen through
 * more of an angle, so near things balloon and far things shrink away from
 * them. It was 800 (a normal lens) and the ground came out nearly flat —
 * the tile at the bottom of the screen was only 6x the one at the haze. At
 * 520 that spread doubles to 12x and the nearest tile grows half again,
 * which is the fisheye read.
 * Every layer's RESTING size and position survive the change untouched:
 * they are authored as what you see at p=0 and multiplied by proj(z) into
 * layout, so the lens divides back out. What changes is everything that
 * depends on relative depth — parallax, the head-tracking swing, and the
 * rate at which a layer swells as it comes at you.
 * The four constants below are all measured in px of depth, so all four are
 * lens-relative and were re-derived when it changed. */
